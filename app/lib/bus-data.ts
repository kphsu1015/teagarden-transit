export type BusRoute = "A" | "B";

/** 民宿最近站，官方公車站牌上「龍頭」「龍頭坪」為相鄰兩站，統一以此名稱顯示 */
export const HOMESTAY_STOP = "龍頭站/龍頭坪站(茶香花園民宿)";

export interface BusRun {
  /** 各站發車時間，順序需與該方向 stops 陣列一致；null 表示不停靠 */
  times: (string | null)[];
}

export interface RouteDirectionData {
  stops: string[];
  runs: BusRun[];
}

export interface RouteData {
  id: BusRoute;
  /** 官方路線編號，A線=7329、B線=7322 */
  number: string;
  /** 顯示於班次查詢結果的簡短標籤，如「7329 台灣好行A線」 */
  shortLabel: string;
  label: string;
  originLabel: string;
  outbound: RouteDirectionData; // 前往阿里山
  inbound: RouteDirectionData; // 返回嘉義
  /** 以 outbound.stops 順序為準的累計票價（從起點站算起），用來換算任兩站區間的參考票價 */
  fareFull: number[];
  fareHalf: number[];
}


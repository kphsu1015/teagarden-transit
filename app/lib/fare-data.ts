// ───────────── 各路線的站序與票價列 ─────────────
type Method = "cash" | "card";

interface FareTable {
  stations: string[];
  full: number[][];
  half: number[][];
}

const BASE: Record<Method, FareRows> = { cash: CASH_7322, card: CARD_7322 };
const EXTRA_7314: Record<Method, FareRows> = { cash: CASH_7314_EXTRA, card: CARD_7314_EXTRA };

const BRANCH = MAIN_STATIONS.length - 1; // 奮起湖終點站
const SHIZHUO = MAIN_STATIONS.indexOf("石棹");
const HSR = "高鐵嘉義站";
const PALACE = "故宮南院";

function buildTable(routeNo: FareRouteNo, method: Method): FareTable {
  const base = BASE[method];
  if (routeNo === "7322") {
    return { stations: [...MAIN_STATIONS], full: base.full, half: base.half };
  }
  if (routeNo === "7302") {
    // 大雅站…石棹＋奮起湖終點站：取 7322 表的前 18 站，再接奮起湖終點站那一列的前 18 格
    const upTo = SHIZHUO + 1;
    return {
      stations: [...MAIN_STATIONS.slice(0, upTo), MAIN_STATIONS[BRANCH]],
      full: [...base.full.slice(0, SHIZHUO), base.full[BRANCH - 1].slice(0, upTo)],
      half: [...base.half.slice(0, SHIZHUO), base.half[BRANCH - 1].slice(0, upTo)],
    };
  }
  if (routeNo === "7314") {
    const upTo = SHIZHUO + 1;
    const extra = EXTRA_7314[method];
    return {
      stations: [...MAIN_STATIONS.slice(0, upTo), ...STATIONS_7314_EXTRA],
      full: [...base.full.slice(0, SHIZHUO), ...extra.full],
      half: [...base.half.slice(0, SHIZHUO), ...extra.half],
    };
  }
  // 7329：高鐵嘉義站 + 頂六國小…奮起湖終點站（沿用 7322 表中這些站之間的票價）+ 故宮南院
  const start = MAIN_STATIONS.indexOf("頂六國小");
  const hsr = HSR_FARES[method];
  const palace = PALACE_FARES[method];
  const shared = MAIN_STATIONS.slice(start);
  const full: number[][] = [];
  const half: number[][] = [];
  shared.forEach((_, k) => {
    const j = start + k; // 在 7322 站序中的位置
    full.push([hsr.full[k], ...base.full[j - 1].slice(start)]);
    half.push([hsr.half[k], ...base.half[j - 1].slice(start)]);
  });
  full.push(palace.full);
  half.push(palace.half);
  return { stations: [HSR, ...shared, PALACE], full, half };
}

const TABLES = new Map<string, FareTable>();
for (const routeNo of ["7322", "7329", "7302", "7314"] as FareRouteNo[]) {
  for (const method of ["cash", "card"] as Method[]) TABLES.set(`${routeNo}:${method}`, buildTable(routeNo, method));
}

/** 提供測試檢查用：取得某路線某付款方式的完整站序與票價列 */
export function getFareTable(routeNo: FareRouteNo, method: Method): FareTable {
  return TABLES.get(`${routeNo}:${method}`)!;
}

// ───────────── 網站站名 → 官方票價表站名 ─────────────
// 官方票價表沒有「觸口遊客中心」「愛情大草原」，這兩站都在觸口聚落（班表上與觸口相差 1～3 分鐘），
// 依官方分站以「觸口」計價。
const OFFICIAL_STATION_BY_APP_STOP: Record<string, string> = {
  嘉義大雅站: "大雅站",
  觸口遊客中心: "觸口",
  愛情大草原: "觸口",
  [HOMESTAY_STOP]: "龍頭坪",
  奮起湖: "奮起湖終點站",
};

export function officialFareStation(appStop: string): string {
  return OFFICIAL_STATION_BY_APP_STOP[appStop] ?? appStop;
}

function pairFrom(table: FareTable, a: string, b: string): FarePair | null {
  const ia = table.stations.indexOf(a);
  const ib = table.stations.indexOf(b);
  if (ia === -1 || ib === -1 || ia === ib) return null;
  const [lo, hi] = ia < ib ? [ia, ib] : [ib, ia];
  const full = table.full[hi - 1]?.[lo];
  const half = table.half[hi - 1]?.[lo];
  return full == null || half == null ? null : { full, half };
}

/** 查兩站之間的官方票價（現金＋刷卡）；任一站不在該路線票價表、或兩站同屬一個計價站時回傳 null */
export function lookupFare(routeNo: FareRouteNo, originStop: string, destStop: string): FareQuote | null {
  const a = officialFareStation(originStop);
  const b = officialFareStation(destStop);
  const cash = pairFrom(getFareTable(routeNo, "cash"), a, b);
  const card = pairFrom(getFareTable(routeNo, "card"), a, b);
  return cash && card ? { cash, card } : null;
}
